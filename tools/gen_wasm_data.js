// Regenerate the embedded base64 WebAssembly binary from web/spid3r.wasm.
// Output: web/spid3r_wasm_data.js (canonical SDK distribution and playground source)
// Usage: node tools/gen_wasm_data.js [outPath]
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const wasmBytes = fs.readFileSync(path.join(root, 'web', 'spid3r.wasm'));
const b64 = wasmBytes.toString('base64');
const content = `// Auto-generated embedded base64 WebAssembly binary for Spid3r
// Enables docs/html/playground.html to run 100% offline and standalone even on file:// URLs
// Generated by tools/gen_wasm_data.js from web/spid3r.wasm — do not hand-edit.
(function(g) {
  g.__SPID3R_WASM_BASE64__ = "${b64}";
})(typeof window !== 'undefined' ? window : (typeof globalThis !== 'undefined' ? globalThis : this));
`;

const outArg = process.argv[2];
const outPath = outArg
  ? path.resolve(outArg)
  : path.join(root, 'web', 'spid3r_wasm_data.js');
fs.writeFileSync(outPath, content, 'utf8');
console.log('Successfully generated ' + path.relative(root, outPath).replace(/\\/g, '/') +
  ' (' + (content.length / 1024 / 1024).toFixed(2) + ' MB, embeds ' + wasmBytes.length + ' bytes)');
