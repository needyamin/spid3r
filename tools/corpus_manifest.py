#!/usr/bin/env python3
"""Frozen self-host corpus manifest (docs/SELFHOST.md SH-4, roadmap 0.3).

The corpus under selfhost/corpus/ is the exact program set every self-host
parity gate (Phases 1-7) runs against. This tool:

  build   regenerate the GENERATED parts of the corpus from their in-tree
          sources (the 24 runnable examples from examples/*.matrix, the
          engine-matrix programs extracted from tests/engine_matrix.rs),
          keep the AUTHORED parts (edge/, negative/) untouched, and write
          MANIFEST.sha256 (sha256 of every corpus file, one `hash  path`
          line, POSIX '/' separators).

  verify  check every corpus file against the manifest — no regeneration.
          Exit 0 = frozen set intact; exit 1 = drift (missing, extra or
          changed file). CI runs this; drift blocks the merge, and a corpus
          change requires a ledger entry in full_plan.html stating why.

The generated parts are marked with a header comment; hand-edits to them are
overwritten by `build`. Authoring changes belong in examples/, in
tests/engine_matrix.rs, or in the authored directories — followed by `build`
and a ledger entry.
"""

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "selfhost" / "corpus"
MANIFEST = CORPUS / "MANIFEST.sha256"

EXAMPLES_DIR = ROOT / "examples"
MATRIX_RS = ROOT / "tests" / "engine_matrix.rs"

# Directories whose files are authored by hand (frozen as committed).
AUTHORED = ("edge", "negative")

GENERATED_HEADER = (
    "// GENERATED by tools/corpus_manifest.py from {source} — do not hand-edit.\n"
    "// Frozen corpus (SH-4): changes require a ledger entry in full_plan.html.\n"
)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract_engine_matrix(rs_text: str):
    """Extract (name, program) pairs from tests/engine_matrix.rs Case blocks.

    The Rust literals are plain string literals with standard escapes; this
    handles \\n \\t \\r \\" \\' \\\\ and \\u{...}, which is the full escape set
    the matrix file uses.
    """
    import re

    cases = []
    # One Case { ... } block at a time; name and src come in order.
    pat = re.compile(r"(?m)^\s+Case\s*\{")
    for m in pat.finditer(rs_text):
        start = m.end()
        depth = 1
        i = start
        while depth > 0 and i < len(rs_text):
            c = rs_text[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            i += 1
        block = rs_text[start : i - 1]

        def field(fname: str, allow_raw: bool = False):
            """The literal content of `fname: "…"` (unescaped) or
            `fname: r#"…"#` (raw, verbatim) — whichever the case uses."""
            fm = re.search(rf'\b{fname}:\s*"((?:[^"\\]|\\.)*)"', block, re.S)
            if fm:
                return fm.group(1), False
            if allow_raw:
                fm = re.search(rf'\b{fname}:\s*r#"((?:.)*?)"#', block, re.S)
                if fm:
                    return fm.group(1), True
            raise SystemExit(f"engine-matrix Case without {fname}")

        (name, _) = field("name")
        (raw, is_raw) = field("src", allow_raw=True)
        if is_raw:
            cases.append((name, raw))
            continue
        # Unescape the Rust string literal.
        out = []
        i = 0
        while i < len(raw):
            c = raw[i]
            if c != "\\":
                out.append(c)
                i += 1
            else:
                nxt = raw[i + 1]
                simple = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "'": "'", "\\": "\\"}
                if nxt in simple:
                    out.append(simple[nxt])
                    i += 2
                elif nxt == "u":
                    end = raw.index("}", i)
                    cp = int(raw[i + 3 : end], 16)
                    out.append(chr(cp))
                    i = end + 1
                else:
                    raise SystemExit(f"unhandled escape \\{nxt} in case {name}")
        cases.append((name, "".join(out)))
    return cases


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8", newline="") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def build() -> int:
    if not MATRIX_RS.is_file():
        print("missing tests/engine_matrix.rs", file=sys.stderr)
        return 1
    changed = []

    # examples/ — the runnable programs only, with a generated header.
    if not EXAMPLES_DIR.is_dir():
        print("missing examples/", file=sys.stderr)
        return 1
    n_examples = 0
    for f in sorted(EXAMPLES_DIR.glob("*.matrix")):
        text = f.read_text(encoding="utf-8")
        if "fn main" not in text:
            continue
        n_examples += 1
        header = GENERATED_HEADER.format(source="examples/" + f.name)
        out = CORPUS / "examples" / f.name
        out.parent.mkdir(parents=True, exist_ok=True)
        if write_if_changed(out, header + text):
            changed.append(out.name)

    # engine_matrix/ — extracted from the Rust conformance matrix.
    cases = extract_engine_matrix(MATRIX_RS.read_text(encoding="utf-8"))
    n_matrix = 0
    for name, program in cases:
        n_matrix += 1
        header = GENERATED_HEADER.format(source="tests/engine_matrix.rs#" + name)
        out = CORPUS / "engine_matrix" / f"{name}.matrix"
        out.parent.mkdir(parents=True, exist_ok=True)
        if write_if_changed(out, header + program):
            changed.append("engine_matrix/" + name)

    return write_manifest(changed, n_examples, n_matrix)


def write_manifest(changed, n_examples, n_matrix) -> int:
    for d in AUTHORED:
        (CORPUS / d).mkdir(parents=True, exist_ok=True)

    lines = []
    for f in sorted(CORPUS.rglob("*")):
        if not f.is_file() or f == MANIFEST:
            continue
        rel = f.relative_to(CORPUS).as_posix()
        lines.append(f"{sha256(f.read_bytes())}  {rel}")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    n_edge = len(list((CORPUS / "edge").glob("*.matrix")))
    n_neg = len(list((CORPUS / "negative").glob("*.matrix")))
    total = n_examples + n_matrix + n_edge + n_neg
    print(
        f"corpus: {n_examples} examples + {n_matrix} engine-matrix "
        f"+ {n_edge} edge + {n_neg} negative = {total} programs; "
        f"manifest: {len(lines)} files"
    )
    if changed:
        print("CHANGED (needs a ledger entry): " + ", ".join(changed))
    return 0


def verify() -> int:
    if not MANIFEST.is_file():
        print("missing MANIFEST.sha256 — run `build` first", file=sys.stderr)
        return 1
    expected = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        h, rel = line.split("  ", 1)
        expected[rel] = h

    actual = {}
    for f in sorted(CORPUS.rglob("*")):
        if not f.is_file() or f == MANIFEST:
            continue
        actual[f.relative_to(CORPUS).as_posix()] = sha256(f.read_bytes())

    problems = []
    for rel, h in expected.items():
        if rel not in actual:
            problems.append(f"missing: {rel}")
        elif actual[rel] != h:
            problems.append(f"changed: {rel}")
    for rel in actual:
        if rel not in expected:
            problems.append(f"extra: {rel}")

    if problems:
        print("CORPUS DRIFT — a ledger entry is required (full_plan.html):")
        for p in problems:
            print("  " + p)
        return 1
    print(f"corpus frozen: {len(expected)} files verified against MANIFEST.sha256")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "build":
        sys.exit(build())
    elif cmd == "verify":
        sys.exit(verify())
    else:
        print("usage: python tools/corpus_manifest.py build|verify", file=sys.stderr)
        sys.exit(2)
