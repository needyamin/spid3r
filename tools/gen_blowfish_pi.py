"""Generate Blowfish's P/S tables from the hexadecimal expansion of pi.

The Blowfish spec defines P (18 words) and S (4 x 256 words) as the fractional
hex digits of pi, so we compute them instead of pasting a table we cannot
verify. 1042 words = 8336 hex digits.
"""
from decimal import Decimal, getcontext

WORDS = 18 + 4 * 256          # 1042
DIGITS = WORDS * 8            # 8336 hex digits (8 per u32)

getcontext().prec = int(DIGITS * 1.21) + 60  # hex digit ~ 1.204 decimal digits

# Compute pi with Machin's formula in high precision decimal.
def arctan_inv(x: int) -> Decimal:
    total = term = Decimal(1) / x
    x2 = x * x
    n = 1
    sign = -1
    while True:
        term = term / x2
        n += 2
        add = term / n
        if add == 0:
            break
        total += sign * add
        sign = -sign
    return total

pi = 4 * (4 * arctan_inv(5) - arctan_inv(239))

frac = pi - 3
scaled = int(frac * (16 ** DIGITS))
# scaled = (pi-3) * 16**DIGITS, so its LOW digits are the fraction;
# the high digit(s) are the integer part of pi.
hexdigits = format(scaled, "x").rjust(DIGITS, "0")[-DIGITS:]

words = [int(hexdigits[i * 8:(i + 1) * 8], 16) for i in range(WORDS)]

assert words[0] == 0x243F6A88, hex(words[0])
assert words[1] == 0x85A308D3, hex(words[1])
assert words[2] == 0x13198A2E, hex(words[2])
assert words[3] == 0x03707344, hex(words[3])

lines = []
lines.append("/// Blowfish P-array and S-boxes: the fractional hexadecimal digits of pi,")
lines.append("/// as the spec defines them (generated by `tools/gen_blowfish_pi.py`, not")
lines.append("/// transcribed — the first four words are asserted against the published")
lines.append("/// constants).")
lines.append("pub const P_INIT: [u32; 18] = [")
for i in range(0, 18, 4):
    chunk = ", ".join("0x%08x" % w for w in words[i:min(i + 4, 18)])
    lines.append("    %s," % chunk)
lines.append("];")
lines.append("")
lines.append("pub const S_INIT: [[u32; 256]; 4] = [")
for box in range(4):
    lines.append("    [")
    start = 18 + box * 256
    for i in range(0, 256, 4):
        chunk = ", ".join("0x%08x" % w for w in words[start + i:start + i + 4])
        lines.append("        %s," % chunk)
    lines.append("    ],")
lines.append("];")

with open("src/stdlib/blowfish_tables.rs", "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print("wrote", WORDS, "words; first:", hex(words[0]), hex(words[1]), hex(words[2]), hex(words[3]))
