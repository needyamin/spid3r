//! Build script for the Spid3r compiler.
//!
//! Two jobs:
//!
//! 1. **Windows installer** (`cargo build --release` on Windows): writes
//!    `Spid3r-Setup-<version>.exe` to the repository root with NSIS. See
//!    [`windows_installer`]. Set `SPID3R_NO_INSTALLER=1` to skip it.
//! 2. **LLVM linking** for the `native` (AOT backend) feature, below.
//!
//! `inkwell`/`llvm-sys` are built with `no-llvm-linking` because llvm-sys does
//! not support dynamic LLVM linking on Windows and requires `llvm-config`
//! elsewhere; instead we link the LLVM C API library ourselves:
//!
//! - Windows: `LLVM-C.lib` (import library for `LLVM-C.dll`, which the official
//!   LLVM installer ships) found via `SPID3R_LLVM_LIB_DIR`, else
//!   `LLVM_SYS_181_PREFIX`, else the default install path.
//! - Linux/macOS: `llvm-config --libdir` + `-lLLVM-N`, else Homebrew prefixes.
//!
//! On Windows we also copy `LLVM-C.dll` next to the built binaries so
//! `cargo run` / `cargo test` work without touching PATH.

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

/// WebView2 bootstrapper acquisition: opt-in, checksum-verified, fail-closed
/// (audit A-11). Kept in its own file so `tests/artifact_hardening.rs` can
/// exercise the exact logic the build runs.
#[path = "build_support/webview2.rs"]
mod webview2;

fn main() {
    // Files this script `#[path]`-includes are build inputs too: without these
    // directives a change to the hash implementation or the WebView2 policy
    // would not rerun the build script.
    println!("cargo:rerun-if-changed=build_support/webview2.rs");
    println!("cargo:rerun-if-changed=src/pkg/sha256.rs");
    // The host triple the toolchain was actually built for.
    //
    // `default_triple()` in `src/native/link.rs` used to be a hand-written
    // table, so on a `*-windows-gnu` or `*-linux-musl` host it reported the
    // MSVC/glibc triple and `spid3r build --target <host>` rejected the host's
    // own triple. Cargo already knows the answer; pass it through.
    println!("cargo:rerun-if-env-changed=TARGET");
    if let Ok(target) = env::var("TARGET") {
        if !target.is_empty() {
            println!("cargo:rustc-env=SPID3R_TARGET={target}");
        }
    }
    if env::var_os("CARGO_FEATURE_NATIVE").is_some() {
        native_llvm();
    }
    embedded_stdlib();
    windows_installer();
    if env::var_os("CARGO_CFG_TARGET_OS").as_deref() == Some(std::ffi::OsStr::new("windows")) {
        windows_resources();
    }
}

/// Emit the `stdlib/*.matrix` sources as a static table for the wasm build.
///
/// A browser has no filesystem, so `import "json"` would otherwise fail with
/// "cannot import". The table is only compiled for wasm32 (see
/// `src/stdlib_embed.rs`); native builds keep reading the files from disk so a
/// project-local `stdlib/` still wins.
fn embedded_stdlib() {
    println!("cargo:rerun-if-changed=stdlib");
    let out_dir = match env::var("OUT_DIR") {
        Ok(d) => PathBuf::from(d),
        Err(_) => return,
    };
    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(read) = fs::read_dir("stdlib") {
        for entry in read.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("matrix") {
                continue;
            }
            if let Some(stem) = path.file_stem().and_then(|s| s.to_str()) {
                entries.push((stem.to_string(), path));
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));
    let mut src = String::from(
        "// Generated by build.rs: the stdlib sources, for targets without a filesystem.\n\
         pub static EMBEDDED_STDLIB: &[(&str, &str)] = &[\n",
    );
    for (name, path) in entries {
        let abs = fs::canonicalize(&path).unwrap_or(path);
        // `include_str!` with an absolute path: the generated file lives in
        // OUT_DIR, so relative paths would not resolve.
        src.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            name,
            abs.to_string_lossy()
        ));
    }
    src.push_str("];\n");
    let dest = out_dir.join("embedded_stdlib.rs");
    if fs::write(&dest, src).is_err() {
        println!("cargo:warning=could not write embedded_stdlib.rs");
    }
}

/// Build `Spid3r-Setup-<version>.exe` for `cargo build --release` on Windows.
///
/// A build script runs before its own crate is compiled, so the installer's
/// `spid3r.exe` comes from a nested release build into `<target>/installer`
/// (same features, guarded against recursion by `SPID3R_INSTALLER_NESTED`).
/// NSIS is taken from `packaging/nsis/nsis/nsis-3.10/` or `PATH`; without it
/// the step is skipped with a warning.
fn windows_installer() {
    println!("cargo:rerun-if-env-changed=SPID3R_NO_INSTALLER");
    println!("cargo:rerun-if-env-changed=SPID3R_PACKAGE");
    println!("cargo:rerun-if-env-changed=SPID3R_BUILD_INSTALLER");
    println!("cargo:rerun-if-env-changed=SPID3R_INSTALLER");

    let is_env_truthy = |val: &str| {
        let v = val.trim();
        v == "1"
            || v.eq_ignore_ascii_case("true")
            || v.eq_ignore_ascii_case("yes")
            || v.eq_ignore_ascii_case("on")
    };
    let is_env_falsy = |val: &str| {
        let v = val.trim();
        v == "0"
            || v.eq_ignore_ascii_case("false")
            || v.eq_ignore_ascii_case("no")
            || v.eq_ignore_ascii_case("off")
    };

    let no_installer = env::var("SPID3R_NO_INSTALLER")
        .map(|v| v.trim().is_empty() || is_env_truthy(&v))
        .unwrap_or(false);

    let explicit_disable = [
        "SPID3R_PACKAGE",
        "SPID3R_BUILD_INSTALLER",
        "SPID3R_INSTALLER",
    ]
    .iter()
    .any(|key| env::var(key).map(|v| is_env_falsy(&v)).unwrap_or(false));

    let packaging_requested = [
        "SPID3R_PACKAGE",
        "SPID3R_BUILD_INSTALLER",
        "SPID3R_INSTALLER",
    ]
    .iter()
    .any(|key| env::var(key).map(|v| is_env_truthy(&v)).unwrap_or(false));

    let is_release = env::var("PROFILE").as_deref() == Ok("release");

    if (!is_release && !packaging_requested)
        || env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows")
        || no_installer
        || explicit_disable
        || env::var_os("SPID3R_INSTALLER_NESTED").is_some()
    {
        return;
    }
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    let version = env::var("CARGO_PKG_VERSION").unwrap_or_default();
    let installer_name = format!("Spid3r-Setup-{version}.exe");
    let installer_path = root.join(&installer_name);
    for input in [
        "src",
        "build.rs",
        "Cargo.toml",
        "Cargo.lock",
        "README.md",
        "docs",
        "examples",
        "benchmarks",
        "stdlib",
        "examples/demo_apps",
        "packaging/nsis/spid3r.nsi",
        "packaging/nsis/LICENSE.txt",
        "packaging/nsis/assets",
    ] {
        println!("cargo:rerun-if-changed={}", root.join(input).display());
    }

    let nsis_dir = root.join("packaging").join("nsis");
    let makensis = [
        Some(nsis_dir.join("nsis").join("nsis-3.10").join("makensis.exe")),
        Some(nsis_dir.join("nsis").join("makensis.exe")),
        Some(PathBuf::from(r"C:\Program Files (x86)\NSIS\makensis.exe")),
        Some(PathBuf::from(r"C:\Program Files\NSIS\makensis.exe")),
        find_on_path("makensis.exe"),
    ]
    .into_iter()
    .flatten()
    .find(|p| p.is_file());
    let Some(makensis) = makensis else {
        println!(
            "cargo:warning=installer skipped: makensis.exe not found \
             (put NSIS 3.x in packaging/nsis/nsis/nsis-3.10/ or on PATH)"
        );
        return;
    };

    // <target>/<profile>/build/<pkg>-<hash>/out -> <target>
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap_or_default());
    let target_root = env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .or_else(|| out_dir.ancestors().nth(4).map(|p| p.to_path_buf()))
        .unwrap_or_else(|| root.join("target"));
    let nested_dir = target_root.join("installer");
    let triple = env::var("TARGET").unwrap_or_default();
    let gui = env::var_os("CARGO_FEATURE_GUI").is_some();
    let native = env::var_os("CARGO_FEATURE_NATIVE").is_some();
    let mut features = Vec::new();
    if gui {
        features.push("gui");
    }
    if native {
        features.push("native");
    }
    // `spid3r build` needs LLVM-C.dll to start, plus LLVM-C.lib and the
    // runtime staticlib to link programs; all three ship next to spid3r.exe.
    let mut native_files = Vec::new();
    if native {
        match (windows_llvm_dll(), windows_llvm_lib_dir()) {
            (Some(dll), Some(lib_dir)) => {
                native_files.push(("LLVM_DLL", dll));
                native_files.push(("LLVM_LIB", lib_dir.join("LLVM-C.lib")));
            }
            _ => {
                println!(
                    "cargo:warning=installer skipped: the native backend needs LLVM-C.dll \
                     and LLVM-C.lib (install LLVM 18.1+; see docs/BUILDING.md)"
                );
                return;
            }
        }
    }

    let cargo = env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let mut build = Command::new(cargo);
    build
        .current_dir(&root)
        .args(["build", "--release", "--bin", "spid3r"]);
    if gui {
        build.args(["--bin", "calculator"]);
    }
    build
        .args(["--lib", "--no-default-features"])
        .arg("--target")
        .arg(&triple)
        .arg("--target-dir")
        .arg(&nested_dir)
        .env("SPID3R_INSTALLER_NESTED", "1");
    if !features.is_empty() {
        build.arg("--features").arg(features.join(","));
    }
    match build.status() {
        Ok(s) if s.success() => {}
        Ok(s) => {
            println!("cargo:warning=installer skipped: nested release build failed ({s})");
            return;
        }
        Err(e) => {
            println!("cargo:warning=installer skipped: cannot run cargo: {e}");
            return;
        }
    }
    let release_dir = if nested_dir
        .join(&triple)
        .join("release")
        .join("spid3r.exe")
        .is_file()
    {
        nested_dir.join(&triple).join("release")
    } else if nested_dir.join("release").join("spid3r.exe").is_file() {
        nested_dir.join("release")
    } else if target_root
        .join(&triple)
        .join("release")
        .join("spid3r.exe")
        .is_file()
    {
        target_root.join(&triple).join("release")
    } else if target_root.join("release").join("spid3r.exe").is_file() {
        target_root.join("release")
    } else {
        nested_dir.join(&triple).join("release")
    };
    let exe = release_dir.join("spid3r.exe");
    if !exe.is_file() {
        println!(
            "cargo:warning=installer skipped: {} not found",
            exe.display()
        );
        return;
    }
    let calc_exe = release_dir.join("calculator.exe");
    if native {
        native_files.push(("RUNTIME_LIB", release_dir.join("spid3r_lang.lib")));
    }
    let webview2 = if gui {
        webview2_bootstrapper(&nsis_dir)
    } else {
        None
    };

    let mut nsis = Command::new(&makensis);
    nsis.current_dir(&nsis_dir)
        .arg("/V2")
        .arg(format!("/DAPPVERSION={version}"))
        .arg(format!("/DOUTFILE={}", installer_path.display()))
        .arg(format!("/DWITH_GUI={}", if gui { 1 } else { 0 }))
        .arg(format!("/DWITH_NATIVE={}", if native { 1 } else { 0 }))
        .arg(format!("/DSPID3R_EXE={}", exe.display()));
    if gui && calc_exe.is_file() {
        nsis.arg(format!("/DCALCULATOR_EXE={}", calc_exe.display()));
    }
    for (name, path) in &native_files {
        nsis.arg(format!("/D{name}={}", path.display()));
    }
    if let Some(setup) = &webview2 {
        nsis.arg(format!("/DWEBVIEW2_SETUP={}", setup.display()));
    }
    let output = nsis.arg("spid3r.nsi").output();
    match output {
        Ok(o) if o.status.success() && installer_path.is_file() => println!(
            "cargo:warning=installer written: {}",
            installer_path.display()
        ),
        Ok(o) if o.status.success() => {
            println!(
                "cargo:warning=installer skipped: makensis reported success but {} was not found",
                installer_path.display()
            );
        }
        Ok(o) => {
            let log = String::from_utf8_lossy(&o.stdout).to_string()
                + &String::from_utf8_lossy(&o.stderr);
            for line in log.lines().filter(|l| !l.trim().is_empty()) {
                println!("cargo:warning=makensis: {line}");
            }
            println!(
                "cargo:warning=installer skipped: makensis failed ({})",
                o.status
            );
        }
        Err(e) => println!("cargo:warning=installer skipped: cannot run makensis: {e}"),
    }
}

/// Microsoft's Evergreen WebView2 bootstrapper, bundled only when the operator
/// opts in and the download verifies (see `build_support/webview2.rs`). A plain
/// release build performs **no** network access; a partial or tampered download
/// is discarded instead of being cached as usable (audit A-11).
fn webview2_bootstrapper(nsis_dir: &std::path::Path) -> Option<PathBuf> {
    println!("cargo:rerun-if-env-changed=SPID3R_FETCH_WEBVIEW2");
    println!("cargo:rerun-if-env-changed=SPID3R_WEBVIEW2_SHA256");
    webview2::ensure(nsis_dir)
}

fn find_on_path(exe: &str) -> Option<PathBuf> {
    env::split_paths(&env::var_os("PATH")?)
        .map(|dir| dir.join(exe))
        .find(|p| p.is_file())
}

fn native_llvm() {
    println!("cargo:rerun-if-env-changed=SPID3R_LLVM_LIB_DIR");
    println!("cargo:rerun-if-env-changed=LLVM_SYS_181_PREFIX");
    println!("cargo:rerun-if-env-changed=SPID3R_LLVM_BIN_DIR");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();

    if target_os == "windows" {
        windows_llvm();
    } else {
        unix_llvm();
    }

    // Drop LLVM-C.dll next to the produced binaries (Windows) so `cargo run`,
    // `cargo test` (whose test executables live in deps/), and the installer
    // work without LLVM's bin directory on PATH.
    if target_os == "windows" {
        if let Some(dll) = windows_llvm_dll() {
            let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap_or_default());
            // <target>/<profile>/build/<pkg>-<hash>/out -> <target>/<profile>
            if let Some(profile) = out_dir.ancestors().nth(3) {
                for dir in [profile.to_path_buf(), profile.join("deps")] {
                    let _ = fs::create_dir_all(&dir);
                    let _ = fs::copy(&dll, dir.join("LLVM-C.dll"));
                }
            }
        } else {
            println!(
                "cargo:warning=LLVM-C.dll not found; spid3r.exe will need LLVM's bin \
                 directory on PATH (or set SPID3R_LLVM_BIN_DIR). See docs/BUILDING.md."
            );
        }
    }
}

/// Directory holding `LLVM-C.lib` (Windows).
fn windows_llvm_lib_dir() -> Option<PathBuf> {
    [
        env::var_os("SPID3R_LLVM_LIB_DIR").map(PathBuf::from),
        env::var_os("LLVM_SYS_181_PREFIX").map(|p| PathBuf::from(p).join("lib")),
        Some(PathBuf::from(r"C:\Program Files\LLVM\lib")),
        Some(PathBuf::from(r"C:\Program Files (x86)\LLVM\lib")),
    ]
    .into_iter()
    .flatten()
    .find(|d| d.join("LLVM-C.lib").is_file())
}

/// `LLVM-C.dll` (Windows), which a native-enabled spid3r.exe loads at startup.
fn windows_llvm_dll() -> Option<PathBuf> {
    [
        env::var_os("SPID3R_LLVM_BIN_DIR").map(PathBuf::from),
        env::var_os("LLVM_SYS_181_PREFIX").map(|p| PathBuf::from(p).join("bin")),
        Some(PathBuf::from(r"C:\Program Files\LLVM\bin")),
        Some(PathBuf::from(r"C:\Program Files (x86)\LLVM\bin")),
    ]
    .into_iter()
    .flatten()
    .map(|d| d.join("LLVM-C.dll"))
    .find(|p| p.is_file())
}

fn windows_llvm() {
    match windows_llvm_lib_dir() {
        Some(dir) => {
            let dir = dir.display().to_string();
            println!("cargo:rustc-link-search=native={dir}");
            println!("cargo:rustc-link-lib=dylib=LLVM-C");

            // Delay-load LLVM-C.dll instead of importing it at startup.
            //
            // Only `spid3r build` calls into LLVM; `spid3r gui` and `spid3r exec`
            // never do. As a load-time import the DLL had to sit beside the
            // executable or on PATH, which meant a binary extracted from an
            // embedded payload (`build --bundle-runtime`) died with
            // 0xC0000135 STATUS_DLL_NOT_FOUND on a machine without Spid3r
            // installed — the exact machine that flag exists for.
            //
            // Delay-loading moves the requirement to the first actual LLVM
            // call, so a GUI-only run needs nothing but the system DLLs.
            println!("cargo:rustc-link-arg=/DELAYLOAD:LLVM-C.dll");
            println!("cargo:rustc-link-arg=delayimp.lib");
            // When dead-stripping removes every LLVM reference (release builds,
            // and anything that never calls into the AOT backend) the linker
            // reports LNK4199 for the now-pointless delay-load hook. That is
            // the intended outcome, so keep it out of the build output.
            println!("cargo:rustc-link-arg=-ignore:4199");
        }
        None => {
            println!(
                "cargo:warning=LLVM 18 not found for the `native` backend. \
                 Install LLVM 18.1+ (https://github.com/llvm/llvm-project/releases) \
                 or set SPID3R_LLVM_LIB_DIR. See docs/BUILDING.md."
            );
        }
    }
}

fn unix_llvm() {
    // Prefer llvm-config when available.
    for name in ["llvm-config", "llvm-config-18"] {
        if let Ok(out) = Command::new(name).arg("--libdir").output() {
            if out.status.success() {
                let libdir = String::from_utf8_lossy(&out.stdout).trim().to_string();
                if !libdir.is_empty() {
                    println!("cargo:rustc-link-search=native={libdir}");
                    // Debian/Ubuntu ship the single libLLVM-18 dylib; Homebrew
                    // uses libLLVM. Try both by emitting the versioned name.
                    let prefix = env::var_os("LLVM_SYS_181_PREFIX")
                        .map(|p| p.to_string_lossy().to_string())
                        .unwrap_or_default();
                    if prefix.contains("homebrew") || prefix.contains("Cellar") {
                        println!("cargo:rustc-link-lib=dylib=LLVM");
                    } else {
                        println!("cargo:rustc-link-lib=dylib=LLVM-18");
                        println!("cargo:rustc-link-lib=dylib=LLVM");
                    }
                    return;
                }
            }
        }
    }

    // Homebrew fallback.
    for base in [
        "/opt/homebrew/opt/llvm@18/lib",
        "/usr/local/opt/llvm@18/lib",
    ] {
        if PathBuf::from(base).is_dir() {
            println!("cargo:rustc-link-search=native={base}");
            println!("cargo:rustc-link-lib=dylib=LLVM");
            return;
        }
    }

    println!(
        "cargo:warning=LLVM 18 not found for the `native` backend. \
         Install llvm-18 development packages and llvm-config, or set \
         LLVM_SYS_181_PREFIX. See docs/BUILDING.md."
    );
}

fn windows_resources() {
    let out_dir = match env::var("OUT_DIR") {
        Ok(d) => PathBuf::from(d),
        Err(_) => return,
    };
    let manifest_path = out_dir.join("spid3r.manifest");
    let manifest_content = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <application xmlns="urn:schemas-microsoft-com:asm.v3">
    <windowsSettings>
      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/pm</dpiAware>
      <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2, PerMonitor</dpiAwareness>
      <longPathAware xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">true</longPathAware>
      <activeCodePage xmlns="http://schemas.microsoft.com/SMI/2019/WindowsSettings">UTF-8</activeCodePage>
    </windowsSettings>
  </application>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}"/>
      <supportedOS Id="{1f676c76-80e1-4239-95bb-83d0f6d0da78}"/>
      <supportedOS Id="{4a2f28e3-53b9-4441-ba9c-d69d4a4a6e38}"/>
      <supportedOS Id="{35138b9a-5d96-4fbd-8e2d-a2440225f93a}"/>
    </application>
  </compatibility>
</assembly>"#;
    let _ = fs::write(&manifest_path, manifest_content);

    let manifest_escaped = manifest_path.to_string_lossy().replace('\\', "/");
    let ico_line = {
        let ico_path = PathBuf::from("packaging/nsis/assets/spid3r.ico");
        if ico_path.is_file() {
            let abs_ico = fs::canonicalize(&ico_path).unwrap_or(ico_path);
            Some(format!(
                "1 ICON \"{}\"\n",
                abs_ico.to_string_lossy().replace('\\', "/")
            ))
        } else {
            None
        }
    };

    // Try finding rc.exe from Windows Kits or PATH
    let mut rc_exe = None;
    let base = PathBuf::from(r"C:\Program Files (x86)\Windows Kits\10\bin");
    if let Ok(entries) = fs::read_dir(&base) {
        let mut versions: Vec<PathBuf> = entries
            .flatten()
            .map(|v| v.path())
            .filter(|p| {
                p.file_name()
                    .and_then(|s| s.to_str())
                    .map(|s| s.starts_with("10."))
                    .unwrap_or(false)
            })
            .collect();
        versions.sort();
        if let Some(latest) = versions.last() {
            let cand = latest.join("x64").join("rc.exe");
            if cand.is_file() {
                rc_exe = Some(cand);
            }
        }
    }
    let rc_cmd = rc_exe.unwrap_or_else(|| PathBuf::from("rc.exe"));

    // `rustc-link-arg-bin` applies to exactly one bin target, so each binary
    // needs its own .res. Sharing one would hand calculator.exe version info
    // that claims OriginalFilename "spid3r.exe" — visible in the Properties
    // dialog — and, before this, left it with no icon at all because only the
    // spid3r bin was ever given the resource.
    let mut bins = vec![("spid3r", "Spid3r Language Toolchain", "spid3r.exe")];
    if env::var_os("CARGO_FEATURE_GUI").is_some() {
        bins.push(("calculator", "Spid3r Calculator", "calculator.exe"));
    }

    for (bin, description, original) in bins {
        let rc_path = out_dir.join(format!("{bin}.rc"));
        let res_path = out_dir.join(format!("{bin}.res"));

        let mut rc_content = format!("1 24 \"{}\"\n", manifest_escaped);
        if let Some(ref ico) = ico_line {
            rc_content.push_str(ico);
        }
        rc_content.push_str(&format!(
            r#"1 VERSIONINFO
FILEVERSION 1,0,0,0
PRODUCTVERSION 1,0,0,0
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "FileDescription", "{description}"
            VALUE "FileVersion", "1.0.0.0"
            VALUE "InternalName", "{bin}"
            VALUE "OriginalFilename", "{original}"
            VALUE "ProductName", "Spid3r"
            VALUE "ProductVersion", "1.0.0"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
        ));

        if fs::write(&rc_path, rc_content).is_err() {
            continue;
        }

        match Command::new(&rc_cmd)
            .arg("/nologo")
            .arg("/fo")
            .arg(&res_path)
            .arg(&rc_path)
            .status()
        {
            Ok(status) if status.success() && res_path.is_file() => {
                println!("cargo:rustc-link-arg-bin={}={}", bin, res_path.display());
            }
            Ok(status) => {
                println!("cargo:warning=rc.exe failed for {bin} with status {status}");
            }
            Err(e) => {
                println!("cargo:warning=failed to invoke rc.exe for {bin}: {e}");
            }
        }
    }
}
