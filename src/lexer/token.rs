//! Token kinds. Keywords are distinct from identifiers at the token level.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Keyword {
    Fn,
    Let,
    Const,
    If,
    Elif,
    Else,
    While,
    For,
    In,
    Break,
    Continue,
    Return,
    True,
    False,
    Null,
    And,
    Or,
    Not,
    Import,
    Try,
    Catch,
    Finally,
    Throw,
    Class,
    Interface,
    New,
    SelfKw,
    Public,
    Private,
    Spawn,
    Async,
    Await,
    Extends,
    Implements,
}

impl Keyword {
    /// The source spelling of the keyword.
    pub fn as_str(self) -> &'static str {
        match self {
            Keyword::Fn => "fn",
            Keyword::Let => "let",
            Keyword::Const => "const",
            Keyword::If => "if",
            Keyword::Elif => "elif",
            Keyword::Else => "else",
            Keyword::While => "while",
            Keyword::For => "for",
            Keyword::In => "in",
            Keyword::Break => "break",
            Keyword::Continue => "continue",
            Keyword::Return => "return",
            Keyword::True => "true",
            Keyword::False => "false",
            Keyword::Null => "null",
            Keyword::And => "and",
            Keyword::Or => "or",
            Keyword::Not => "not",
            Keyword::Import => "import",
            Keyword::Try => "try",
            Keyword::Catch => "catch",
            Keyword::Finally => "finally",
            Keyword::Throw => "throw",
            Keyword::Class => "class",
            Keyword::Interface => "interface",
            Keyword::New => "new",
            Keyword::SelfKw => "self",
            Keyword::Public => "public",
            Keyword::Private => "private",
            Keyword::Spawn => "spawn",
            Keyword::Async => "async",
            Keyword::Await => "await",
            Keyword::Extends => "extends",
            Keyword::Implements => "implements",
        }
    }

    pub fn from_ident(s: &str) -> Option<Keyword> {
        Some(match s {
            "fn" => Keyword::Fn,
            "let" => Keyword::Let,
            "const" => Keyword::Const,
            "if" => Keyword::If,
            "elif" => Keyword::Elif,
            "else" => Keyword::Else,
            "while" => Keyword::While,
            "for" => Keyword::For,
            "in" => Keyword::In,
            "break" => Keyword::Break,
            "continue" => Keyword::Continue,
            "return" => Keyword::Return,
            "true" => Keyword::True,
            "false" => Keyword::False,
            "null" => Keyword::Null,
            "and" => Keyword::And,
            "or" => Keyword::Or,
            "not" => Keyword::Not,
            "import" => Keyword::Import,
            "try" => Keyword::Try,
            "catch" => Keyword::Catch,
            "finally" => Keyword::Finally,
            "throw" => Keyword::Throw,
            "class" => Keyword::Class,
            "interface" => Keyword::Interface,
            "new" => Keyword::New,
            "self" => Keyword::SelfKw,
            "public" => Keyword::Public,
            "private" => Keyword::Private,
            "spawn" => Keyword::Spawn,
            "async" => Keyword::Async,
            "await" => Keyword::Await,
            "extends" => Keyword::Extends,
            "implements" => Keyword::Implements,
            _ => return None,
        })
    }
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Int(i64),
    Float(f64),
    Str(String),
    Ident(String),
    Kw(Keyword),

    Plus,
    Minus,
    Star,
    Slash,
    Percent,

    EqEq,
    BangEq,
    Lt,
    Le,
    Gt,
    Ge,

    Assign,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,

    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,

    Comma,
    Colon,
    Semi,
    Dot,
    Arrow,

    Eof,
}

#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub span: crate::diagnostics::Span,
}
